"""Write the Cyberpunk world file into a redscript function, so the mod can send it (mod spec what/world.md rule 12).

The mod cannot read world.json from the game folder, so the JSON text goes into the script.
Run it after each change of world.json:

    uv run python mods/cyberpunk/tools/world_reds.py

A test (mods/cyberpunk/tests/test_mod_files.py) fails if the script is older than world.json.
"""

import json
from pathlib import Path

MOD = Path(__file__).resolve().parents[1]
WORLD = MOD / "world.json"
OUT = MOD / "r6" / "scripts" / "genpc" / "World.reds"


def render(world_text: str) -> str:
    compact = json.dumps(json.loads(world_text), ensure_ascii=True, separators=(",", ":"))
    literal = compact.replace("\\", "\\\\").replace('"', '\\"')
    return (
        "// Generated by mods/cyberpunk/tools/world_reds.py from mods/cyberpunk/world.json. Do not edit.\n"
        "module Genpc\n\n"
        "public func GenpcWorldJson() -> String {\n"
        f'  return "{literal}";\n'
        "}\n"
    )


def main() -> None:
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(WORLD.read_text(encoding="utf-8")))
    print(f"wrote {OUT.relative_to(MOD)}")


if __name__ == "__main__":
    main()
